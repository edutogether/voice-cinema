// 폰트 서브셋이 글자를 빠뜨리지 않는지 지킨다.
//
// 왜 있는가: 처음에는 빌드 산출물만 훑어 글자를 모았는데, 번들러가 한글을
// 유니코드 이스케이프(역슬래시 u 다음 네 자리)로 내보내는 바람에 **140자가 빠졌다**(2026-09-09 실측,
// fontTools로 서브셋 cmap을 직접 읽어 확인). 그대로 배포됐으면 그 글자들이
// 화면에서 두부(□)로 나왔을 것이다.
import { test, expect, describe } from 'vitest';
import { unescapeUnicode, 모은글자를_검사한다 } from '../tools/subset-fonts.js';

describe('unescapeUnicode — 번들러가 감춘 글자를 되살린다', () => {
  test('역슬래시 u 네 자리 형태를 실제 글자로 되돌린다', () => {
    expect(unescapeUnicode('\uac00\ub098')).toBe('가나');
  });

  test('중괄호 형태도 되돌린다', () => {
    expect(unescapeUnicode('\u{ac00}')).toBe('가');
  });

  test('이미 실제 글자인 것은 그대로 둔다', () => {
    expect(unescapeUnicode('판타지')).toBe('판타지');
  });

  test('이스케이프가 아닌 문자열은 건드리지 않는다', () => {
    expect(unescapeUnicode('url(#u123)')).toBe('url(#u123)');
  });
});

// 두 번째 사고 유형: 글자를 **하나도 못 모아도** 빌드가 통과하던 것.
// 서브셋이 원본보다 작아졌는지만 보는 가드는 글자가 적을수록 더 잘 통과하므로
// 이쪽을 전혀 막지 못했다 — 훑을 파일을 0건으로 만들어 보니 한글이 한 글자도 없는
// 95자짜리 폰트가 그대로 빌드됐고 유닛테스트 52개도 전부 통과했다(2026-09-10 실측).
// 그대로 나갔으면 Pretendard가 없는 기기에서 화면의 모든 한글이 두부(□)로 찍힌다.
describe('모은글자를_검사한다 — 아무것도 안 본 상태를 통과로 세지 않는다', () => {
  // 실제로 모이는 것과 같은 성격의 표본. 여기 문구는 검사가 요구하는 것과
  // 별개로 적어둔 것이라, 검사를 느슨하게 바꾸면 이 테스트가 먼저 깨진다.
  const 충분한글자 = [...new Set(
    '무성영화에 내 목소리를 더빙해 완성하는 나만의 영화 판타지 호러 액션 드라마 시트콤 애니메이션 녹음 저장 다시 완성' +
    Array.from({ length: 500 }, (_, i) => String.fromCharCode(0xac00 + i)).join('')
  )].join('');

  test('훑은 파일이 0개면 통과가 아니라 예외다', () => {
    expect(() => 모은글자를_검사한다(충분한글자, 0)).toThrow(/파일을 하나도 찾지 못했습니다/);
  });

  test('화면에 반드시 나오는 문구가 빠지면 예외다', () => {
    const 태그라인없음 = [...충분한글자].filter((c) => !'무성영화'.includes(c)).join('');
    expect(() => 모은글자를_검사한다(태그라인없음, 31)).toThrow(/화면에 반드시 나오는 문구/);
  });

  test('장르 이름 하나만 빠져도 예외다', () => {
    const 호러없음 = [...충분한글자].filter((c) => c !== '호').join('');
    expect(() => 모은글자를_검사한다(호러없음, 31)).toThrow(/호러/);
  });

  test('한글 음절이 바닥 아래로 떨어지면 예외다', () => {
    const 조금만 = '무성영화에 내 목소리를 더빙해 완성하는 나만의 판타지 호러 액션 드라마 시트콤 애니메이션 녹음 저장 다시';
    expect(() => 모은글자를_검사한다(조금만, 31)).toThrow(/한글 음절이/);
  });

  test('정상이면 무엇을 몇 개 봤는지 돌려준다 — 숫자가 없으면 0건 통과와 구별되지 않는다', () => {
    const r = 모은글자를_검사한다(충분한글자, 31);
    expect(r.훑은파일수).toBe(31);
    expect(r.한글수).toBeGreaterThanOrEqual(400);
  });
});
